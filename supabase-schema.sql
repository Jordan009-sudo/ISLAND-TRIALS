create table if not exists public.season_saves (
  user_id uuid primary key references auth.users (id) on delete cascade,
  save_data jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.season_saves enable row level security;

drop policy if exists "Users manage their own season save" on public.season_saves;
create policy "Users manage their own season save"
  on public.season_saves
  for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.season_saves to authenticated;

create table if not exists public.game_rooms (
  id bigint generated by default as identity (start with 1000) primary key,
  host_id uuid not null references auth.users (id) on delete cascade,
  status text not null default 'waiting' check (status in ('waiting', 'started', 'finished')),
  game_config jsonb,
  created_at timestamptz not null default now()
);

alter table public.game_rooms add column if not exists game_config jsonb;

alter table public.game_rooms enable row level security;

drop policy if exists "Signed-in users can view waiting rooms" on public.game_rooms;
drop policy if exists "Anyone can view public game rooms" on public.game_rooms;
create policy "Anyone can view public game rooms"
  on public.game_rooms
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Users create their own rooms" on public.game_rooms;
create policy "Users create their own rooms"
  on public.game_rooms
  for insert
  to authenticated
  with check (host_id = (select auth.uid()));

drop policy if exists "Hosts manage their rooms" on public.game_rooms;
create policy "Hosts manage their rooms"
  on public.game_rooms
  for update
  to authenticated
  using (host_id = (select auth.uid()))
  with check (host_id = (select auth.uid()));

drop policy if exists "Hosts delete their rooms" on public.game_rooms;
create policy "Hosts delete their rooms"
  on public.game_rooms
  for delete
  to authenticated
  using (host_id = (select auth.uid()));

grant select, insert, update, delete on public.game_rooms to authenticated;
grant select on public.game_rooms to anon;
grant usage, select on sequence public.game_rooms_id_seq to authenticated;

notify pgrst, 'reload schema';